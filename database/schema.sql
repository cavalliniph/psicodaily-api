CREATE DOMAIN dm_role AS VARCHAR(20)
CHECK (VALUE IN ('PACIENTE', 'PSICOLOGO', 'PSIQUIATRA'));

CREATE DOMAIN dm_status_sessao AS VARCHAR(20)
CHECK (VALUE IN ('AGENDADO', 'CONFIRMADO', 'REALIZADO', 'CANCELADO'));

CREATE DOMAIN dm_conselho AS VARCHAR(20)
CHECK (VALUE IN ('CRP', 'CRM'));

CREATE DOMAIN dm_nivel_humor AS VARCHAR(20)
CHECK (VALUE IN ('PESSIMO', 'RUIM', 'NEUTRO', 'BOM', 'EXCELENTE'));

CREATE DOMAIN dm_qualidade_sono AS VARCHAR(20)
CHECK (VALUE IN ('RUIM', 'REGULAR', 'BOA', 'EXCELENTE'));

CREATE DOMAIN dm_qualidade_alimentacao AS VARCHAR(20)
CHECK (VALUE IN ('POUCA', 'DESREGULADA', 'ADEQUADA', 'EXCESSIVA'));

CREATE TABLE usuario(
	id_usuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	email varchar(255) NOT NULL,
	nome varchar(150) NOT NULL,
	telefone varchar(20) NOT NULL,
	cpf varchar(11) NOT NULL,
	usuario_role dm_role NOT NULL,
	senha varchar(255),
	codigo varchar(6),
	ativo boolean DEFAULT FALSE NOT NULL
);

CREATE TABLE profissional (
    usuario_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conselho_tipo dm_conselho NOT NULL,
    conselho_numero VARCHAR(20) NOT NULL,
    especialidade VARCHAR(100),
    preco_hora INTEGER NOT NULL,
    descricao BLOB CHARACTER SET UTF8,
    CONSTRAINT FK_PROFISSIONAL_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID_USUARIO) ON DELETE CASCADE
);

CREATE TABLE registro (
    registro_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL,
    humor DM_NIVEL_HUMOR NOT NULL,
    qualidade_sono DM_QUALIDADE_SONO NOT NULL,
    minutos_sono SMALLINT,
    alimentacao DM_QUALIDADE_ALIMENTACAO,
    exercicio_fisico BOOLEAN DEFAULT FALSE,
    interacao SMALLINT,
    anotacao BLOB CHARACTER SET UTF8,
    criado_em DATE DEFAULT CURRENT_DATE NOT NULL,
    CONSTRAINT FK_REGISTRO_USUARIO FOREIGN KEY (USUARIO_ID) 
        REFERENCES USUARIO (ID_USUARIO) ON DELETE CASCADE
);

CREATE TABLE encaminhamento (
    ENCAMINHAMENTO_ID INTEGER NOT NULL PRIMARY KEY,
    PACIENTE_ID INTEGER NOT NULL,
    PSICOLOGO_ID INTEGER NOT NULL,
    CID VARCHAR(10),
    MOTIVO BLOB SUB_TYPE TEXT NOT NULL,
    STATUS DM_STATUS_ENCAMINHAMENTO DEFAULT 'ATIVO' NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_ENCAM_PACIENTE FOREIGN KEY (PACIENTE_ID) 
        REFERENCES USUARIO (USUARIO_ID) ON DELETE CASCADE,
    CONSTRAINT FK_ENCAM_PSICOLOGO FOREIGN KEY (PSICOLOGO_ID) 
        REFERENCES PROFISSIONAL (USUARIO_ID) ON DELETE CASCADE
);

CREATE TABLE CONVERSA (
    CONVERSA_ID INTEGER NOT NULL PRIMARY KEY,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE CONVERSA_PARTICIPANTE (
    CONVERSA_PARTICIPANTE_ID INTEGER NOT NULL PRIMARY KEY,
    USUARIO_ID INTEGER NOT NULL,
    CONVERSA_ID INTEGER NOT NULL,
    CONSTRAINT FK_PARTICIPANTE_USUARIO FOREIGN KEY (USUARIO_ID) 
        REFERENCES USUARIO (USUARIO_ID) ON DELETE CASCADE,
    CONSTRAINT FK_PARTICIPANTE_CONVERSA FOREIGN KEY (CONVERSA_ID) 
        REFERENCES CONVERSA (CONVERSA_ID) ON DELETE CASCADE
);

CREATE TABLE CONVERSA_MENSAGEM (
    CONVERSA_MENSAGEM_ID INTEGER NOT NULL PRIMARY KEY,
    USUARIO_ID INTEGER NOT NULL,
    CONVERSA_ID INTEGER NOT NULL,
    MENSAGEM BLOB SUB_TYPE TEXT NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_MENSAGEM_USUARIO FOREIGN KEY (USUARIO_ID) 
        REFERENCES USUARIO (USUARIO_ID) ON DELETE CASCADE,
    CONSTRAINT FK_MENSAGEM_CONVERSA FOREIGN KEY (CONVERSA_ID) 
        REFERENCES CONVERSA (CONVERSA_ID) ON DELETE CASCADE
);

CREATE TABLE SESSAO (
    SESSAO_ID INTEGER NOT NULL PRIMARY KEY,
    PACIENTE_ID INTEGER NOT NULL,
    PROFISSIONAL_ID INTEGER NOT NULL,
    ENCAMINHAMENTO_ID INTEGER,
    CONVERSA_ID INTEGER,
    DATA_HORA_INICIO TIMESTAMP NOT NULL,
    DATA_HORA_FIM TIMESTAMP NOT NULL,
    STATUS DM_STATUS_SESSAO DEFAULT 'AGENDADA' NOT NULL,
    VALOR DECIMAL(10, 2) NOT NULL,
    LINK_REUNIAO VARCHAR(255),
    CONSTRAINT FK_SESSAO_PACIENTE FOREIGN KEY (PACIENTE_ID) 
        REFERENCES USUARIO (USUARIO_ID) ON DELETE CASCADE,
    CONSTRAINT FK_SESSAO_PROFISSIONAL FOREIGN KEY (PROFISSIONAL_ID) 
        REFERENCES PROFISSIONAL (USUARIO_ID) ON DELETE CASCADE,
    CONSTRAINT FK_SESSAO_ENCAMINHAMENTO FOREIGN KEY (ENCAMINHAMENTO_ID) 
        REFERENCES ENCAMINHAMENTO (ENCAMINHAMENTO_ID) ON DELETE SET NULL,
    CONSTRAINT FK_SESSAO_CONVERSA FOREIGN KEY (CONVERSA_ID) 
        REFERENCES CONVERSA (CONVERSA_ID) ON DELETE SET NULL
);

CREATE INDEX IDX_SESSAO_PACIENTE ON SESSAO (PACIENTE_ID);
CREATE INDEX IDX_SESSAO_PROFISSIONAL ON SESSAO (PROFISSIONAL_ID);

