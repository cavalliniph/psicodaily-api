-- Feature 18: chat paciente x profissional. A conversa e o par; CONVERSA/CONVERSA_MENSAGEM do baseline ficam sem uso
-- (sem IDENTITY e com texto ISO8859_1).
CREATE TABLE MENSAGEM (MENSAGEM_ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
        PACIENTE_ID INTEGER NOT NULL,
        PROFISSIONAL_ID INTEGER NOT NULL,
        REMETENTE_ID INTEGER NOT NULL,
        TEXTO VARCHAR(2000) CHARACTER SET UTF8 NOT NULL,
        LIDA BOOLEAN DEFAULT FALSE NOT NULL,
        CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
PRIMARY KEY (MENSAGEM_ID),
CONSTRAINT CK_MENSAGEM_REMETENTE CHECK (REMETENTE_ID IN (PACIENTE_ID, PROFISSIONAL_ID)));
ALTER TABLE MENSAGEM ADD CONSTRAINT FK_MENSAGEM_PACIENTE FOREIGN KEY (PACIENTE_ID) REFERENCES USUARIO (ID_USUARIO) ON DELETE CASCADE;
ALTER TABLE MENSAGEM ADD CONSTRAINT FK_MENSAGEM_PROFISSIONAL FOREIGN KEY (PROFISSIONAL_ID) REFERENCES PROFISSIONAL (USUARIO_ID) ON DELETE CASCADE;
CREATE INDEX IX_MENSAGEM_PAR ON MENSAGEM (PACIENTE_ID, PROFISSIONAL_ID, MENSAGEM_ID);
CREATE INDEX IX_MENSAGEM_PROFISSIONAL ON MENSAGEM (PROFISSIONAL_ID);
