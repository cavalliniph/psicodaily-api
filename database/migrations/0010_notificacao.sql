-- F3: notificacoes do usuario. TITULO e MENSAGEM prontos para exibir; DADOS e JSON para o front montar links.
CREATE TABLE NOTIFICACAO (NOTIFICACAO_ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
        USUARIO_ID INTEGER NOT NULL,
        TIPO VARCHAR(40) NOT NULL,
        TITULO VARCHAR(150) CHARACTER SET UTF8 NOT NULL,
        MENSAGEM VARCHAR(1000) CHARACTER SET UTF8 NOT NULL,
        DADOS VARCHAR(2000) CHARACTER SET UTF8,
        LIDA BOOLEAN DEFAULT FALSE NOT NULL,
        CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
PRIMARY KEY (NOTIFICACAO_ID));
ALTER TABLE NOTIFICACAO ADD CONSTRAINT FK_NOTIFICACAO_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID_USUARIO) ON DELETE CASCADE;
