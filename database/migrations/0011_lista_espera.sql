-- Feature 6: paciente espera uma vaga com o profissional dentro de uma janela. AVISADO_EM marca quem ja foi avisado.
CREATE TABLE LISTA_ESPERA (LISTA_ESPERA_ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
        PACIENTE_ID INTEGER NOT NULL,
        PROFISSIONAL_ID INTEGER NOT NULL,
        INICIO_DESEJADO TIMESTAMP NOT NULL,
        FIM_DESEJADO TIMESTAMP NOT NULL,
        AVISADO_EM TIMESTAMP,
        CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
PRIMARY KEY (LISTA_ESPERA_ID),
CONSTRAINT CK_LISTA_ESPERA_JANELA CHECK (FIM_DESEJADO > INICIO_DESEJADO));
ALTER TABLE LISTA_ESPERA ADD CONSTRAINT FK_LISTA_ESPERA_PACIENTE FOREIGN KEY (PACIENTE_ID) REFERENCES USUARIO (ID_USUARIO) ON DELETE CASCADE;
ALTER TABLE LISTA_ESPERA ADD CONSTRAINT FK_LISTA_ESPERA_PROFISSIONAL FOREIGN KEY (PROFISSIONAL_ID) REFERENCES PROFISSIONAL (USUARIO_ID) ON DELETE CASCADE;
