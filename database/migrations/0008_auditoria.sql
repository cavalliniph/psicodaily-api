-- F5: log de auditoria. Sem FK de proposito: o registro sobrevive a exclusao do usuario.
CREATE TABLE AUDITORIA (AUDITORIA_ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
        USUARIO_ID INTEGER,
        ACAO VARCHAR(40) NOT NULL,
        ENTIDADE VARCHAR(30),
        ENTIDADE_ID INTEGER,
        IP VARCHAR(45),
        CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
PRIMARY KEY (AUDITORIA_ID));
CREATE INDEX IX_AUDITORIA_USUARIO ON AUDITORIA (USUARIO_ID);
CREATE DESCENDING INDEX IX_AUDITORIA_CRIADO_EM ON AUDITORIA (CRIADO_EM);
