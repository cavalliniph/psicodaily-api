-- Feature 8: artigos e conteudos que o profissional publica no perfil (texto puro ou Markdown).
CREATE TABLE CONTEUDO (CONTEUDO_ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
        PROFISSIONAL_ID INTEGER NOT NULL,
        TITULO VARCHAR(200) CHARACTER SET UTF8 NOT NULL,
        CORPO BLOB SUB_TYPE TEXT SEGMENT SIZE 80 CHARACTER SET UTF8 NOT NULL,
        PUBLICADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
        ATUALIZADO_EM TIMESTAMP,
PRIMARY KEY (CONTEUDO_ID));
ALTER TABLE CONTEUDO ADD CONSTRAINT FK_CONTEUDO_PROFISSIONAL FOREIGN KEY (PROFISSIONAL_ID) REFERENCES PROFISSIONAL (USUARIO_ID) ON DELETE CASCADE;
