-- F1: janelas semanais de atendimento do profissional. DIA_SEMANA segue o EXTRACT(WEEKDAY) do
-- Firebird e o getDay() do JavaScript: 0 = domingo ... 6 = sabado.
CREATE TABLE DISPONIBILIDADE (DISPONIBILIDADE_ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
        PROFISSIONAL_ID INTEGER NOT NULL,
        DIA_SEMANA SMALLINT NOT NULL,
        HORA_INICIO TIME NOT NULL,
        HORA_FIM TIME NOT NULL,
PRIMARY KEY (DISPONIBILIDADE_ID),
CONSTRAINT CK_DISPONIBILIDADE_DIA CHECK (DIA_SEMANA BETWEEN 0 AND 6),
CONSTRAINT CK_DISPONIBILIDADE_HORA CHECK (HORA_FIM > HORA_INICIO));
ALTER TABLE DISPONIBILIDADE ADD CONSTRAINT FK_DISPONIBILIDADE_PROFISSIONAL FOREIGN KEY (PROFISSIONAL_ID) REFERENCES PROFISSIONAL (USUARIO_ID) ON DELETE CASCADE;
