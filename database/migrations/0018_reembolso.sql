-- 24: reembolso integral de pagamento de sessao cancelada. A Arkhé nao estorna: o admin devolve por Pix de saida
-- (ID_MOVIMENTACAO_ARKHE) ou por fora, e marca como pago.
CREATE TABLE REEMBOLSO (REEMBOLSO_ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
        PAGAMENTO_ID INTEGER NOT NULL,
        VALOR_CENTAVOS INTEGER NOT NULL,
        STATUS VARCHAR(10) DEFAULT 'PENDENTE' NOT NULL,
        ID_MOVIMENTACAO_ARKHE INTEGER,
        CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
        PAGO_EM TIMESTAMP,
PRIMARY KEY (REEMBOLSO_ID),
CONSTRAINT UQ_REEMBOLSO_PAGAMENTO UNIQUE (PAGAMENTO_ID),
CONSTRAINT CK_REEMBOLSO_STATUS CHECK (STATUS IN ('PENDENTE', 'PAGO')));
ALTER TABLE REEMBOLSO ADD CONSTRAINT FK_REEMBOLSO_PAGAMENTO FOREIGN KEY (PAGAMENTO_ID) REFERENCES PAGAMENTO (PAGAMENTO_ID) ON DELETE CASCADE;
