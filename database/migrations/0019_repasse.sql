CREATE TABLE REPASSE (REPASSE_ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
        PROFISSIONAL_ID INTEGER NOT NULL,
        VALOR_CENTAVOS INTEGER NOT NULL,
        STATUS VARCHAR(10) DEFAULT 'PENDENTE' NOT NULL,
        ID_MOVIMENTACAO_ARKHE INTEGER,
        CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
        PAGO_EM TIMESTAMP,
PRIMARY KEY (REPASSE_ID),
CONSTRAINT CK_REPASSE_STATUS CHECK (STATUS IN ('PENDENTE', 'PAGO')));
ALTER TABLE REPASSE ADD CONSTRAINT FK_REPASSE_PROFISSIONAL FOREIGN KEY (PROFISSIONAL_ID) REFERENCES USUARIO (ID_USUARIO);
ALTER TABLE PAGAMENTO ADD TAXA_ARKHE_CENTAVOS INTEGER;
ALTER TABLE PAGAMENTO ADD REPASSE_ID INTEGER;
