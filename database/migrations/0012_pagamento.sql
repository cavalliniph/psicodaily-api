-- F2: cobranca da Arkhé ligada a sessao, para checar o dono e saber o que foi pago sem chamar a Arkhé.
CREATE TABLE PAGAMENTO (PAGAMENTO_ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
        SESSAO_ID INTEGER NOT NULL,
        ID_COBRANCA_ARKHE INTEGER NOT NULL,
        METODO VARCHAR(10) DEFAULT 'PIX' NOT NULL,
        VALOR_CENTAVOS INTEGER NOT NULL,
        STATUS VARCHAR(10) DEFAULT 'PENDENTE' NOT NULL,
        CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
        PAGO_EM TIMESTAMP,
PRIMARY KEY (PAGAMENTO_ID),
CONSTRAINT UQ_PAGAMENTO_COBRANCA UNIQUE (ID_COBRANCA_ARKHE),
CONSTRAINT CK_PAGAMENTO_STATUS CHECK (STATUS IN ('PENDENTE', 'PAGO')));
ALTER TABLE PAGAMENTO ADD CONSTRAINT FK_PAGAMENTO_SESSAO FOREIGN KEY (SESSAO_ID) REFERENCES SESSAO (SESSAO_ID) ON DELETE CASCADE;
CREATE INDEX IX_PAGAMENTO_PAGO_EM ON PAGAMENTO (PAGO_EM);
