-- Baseline: schema de producao em 19/10/2026 (commit 43fb231), extraido com isql -x.
-- O banco e criado por migrar.py --criar com PAGE_SIZE 16384 e DEFAULT CHARACTER SET ISO8859_1,
-- como o de producao: VARCHAR sem CHARACTER SET explicito fica em ISO8859_1.
SET SQL DIALECT 3; 



/* Domain definitions */
CREATE DOMAIN DM_CONSELHO AS VARCHAR(20);
CREATE DOMAIN DM_MODALIDADE AS VARCHAR(20);
CREATE DOMAIN DM_NIVEL_HUMOR AS VARCHAR(20);
CREATE DOMAIN DM_QUALIDADE_ALIMENTACAO AS VARCHAR(20);
CREATE DOMAIN DM_QUALIDADE_SONO AS VARCHAR(20);
CREATE DOMAIN DM_ROLE AS VARCHAR(20);
CREATE DOMAIN DM_STATUS_ENCAMINHAMENTO AS VARCHAR(20);
CREATE DOMAIN DM_STATUS_SESSAO AS VARCHAR(20);
COMMIT WORK;

/* Table: AVALIACAO, Owner: SYSDBA */
CREATE TABLE AVALIACAO (AVALIACAO_ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
        SESSAO_ID INTEGER NOT NULL,
        PACIENTE_ID INTEGER NOT NULL,
        PROFISSIONAL_ID INTEGER NOT NULL,
        NOTA SMALLINT NOT NULL,
        COMENTARIO VARCHAR(500),
        CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
PRIMARY KEY (AVALIACAO_ID),
CONSTRAINT UQ_AVALIACAO_SESSAO UNIQUE (SESSAO_ID));

/* Table: CID, Owner: SYSDBA */
CREATE TABLE CID (ID_CID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
        CODIGO VARCHAR(11) NOT NULL,
        DESCRICAO VARCHAR(255) NOT NULL,
        VERSAO VARCHAR(10) NOT NULL,
PRIMARY KEY (ID_CID),
UNIQUE (CODIGO));

/* Table: CONVERSA, Owner: SYSDBA */
CREATE TABLE CONVERSA (CONVERSA_ID INTEGER NOT NULL,
        CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
PRIMARY KEY (CONVERSA_ID));

/* Table: CONVERSA_MENSAGEM, Owner: SYSDBA */
CREATE TABLE CONVERSA_MENSAGEM (CONVERSA_MENSAGEM_ID INTEGER NOT NULL,
        USUARIO_ID INTEGER NOT NULL,
        CONVERSA_ID INTEGER NOT NULL,
        MENSAGEM BLOB SUB_TYPE TEXT SEGMENT SIZE 80 NOT NULL,
        CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
PRIMARY KEY (CONVERSA_MENSAGEM_ID));

/* Table: ENCAMINHAMENTO, Owner: SYSDBA */
CREATE TABLE ENCAMINHAMENTO (ENCAMINHAMENTO_ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
        PACIENTE_ID INTEGER NOT NULL,
        PSICOLOGO_ID INTEGER NOT NULL,
        CID VARCHAR(10),
        MOTIVO BLOB SUB_TYPE TEXT SEGMENT SIZE 80 CHARACTER SET UTF8 NOT NULL,
        STATUS DM_STATUS_ENCAMINHAMENTO DEFAULT 'ATIVO' NOT NULL,
        CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
PRIMARY KEY (ENCAMINHAMENTO_ID));

/* Table: PROFISSIONAL, Owner: SYSDBA */
CREATE TABLE PROFISSIONAL (USUARIO_ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
        CONSELHO_TIPO DM_CONSELHO NOT NULL,
        CONSELHO_NUMERO VARCHAR(20) NOT NULL,
        ESPECIALIDADE VARCHAR(100),
        PRECO_HORA INTEGER NOT NULL,
        DESCRICAO BLOB SUB_TYPE TEXT SEGMENT SIZE 80 CHARACTER SET UTF8,
        ABORDAGEM VARCHAR(100),
        MODALIDADE DM_MODALIDADE,
        FORMACAO VARCHAR(1000),
        ANO_INICIO_ATUACAO SMALLINT,
        IDIOMAS VARCHAR(200),
        AREAS_ATUACAO VARCHAR(400),
        VIDEO_URL VARCHAR(255),
PRIMARY KEY (USUARIO_ID));

/* Table: REGISTRO, Owner: SYSDBA */
CREATE TABLE REGISTRO (REGISTRO_ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
        USUARIO_ID INTEGER NOT NULL,
        HUMOR DM_NIVEL_HUMOR NOT NULL,
        QUALIDADE_SONO DM_QUALIDADE_SONO NOT NULL,
        MINUTOS_SONO SMALLINT,
        ALIMENTACAO DM_QUALIDADE_ALIMENTACAO,
        EXERCICIO_FISICO BOOLEAN DEFAULT FALSE,
        INTERACAO SMALLINT,
        ANOTACAO BLOB SUB_TYPE TEXT SEGMENT SIZE 80 CHARACTER SET UTF8,
        CRIADO_EM DATE DEFAULT CURRENT_DATE NOT NULL,
PRIMARY KEY (REGISTRO_ID));

/* Table: SESSAO, Owner: SYSDBA */
CREATE TABLE SESSAO (SESSAO_ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
        PACIENTE_ID INTEGER NOT NULL,
        PROFISSIONAL_ID INTEGER NOT NULL,
        ENCAMINHAMENTO_ID INTEGER,
        CONVERSA_ID INTEGER,
        DATA_HORA_INICIO TIMESTAMP NOT NULL,
        DATA_HORA_FIM TIMESTAMP NOT NULL,
        STATUS DM_STATUS_SESSAO DEFAULT 'AGENDADA' NOT NULL,
        VALOR_CENTAVOS INTEGER NOT NULL,
        LINK_REUNIAO VARCHAR(255),
        CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
PRIMARY KEY (SESSAO_ID));

/* Table: USUARIO, Owner: SYSDBA */
CREATE TABLE USUARIO (ID_USUARIO INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
        EMAIL VARCHAR(255) NOT NULL,
        NOME VARCHAR(150) NOT NULL,
        TELEFONE VARCHAR(20) NOT NULL,
        CPF VARCHAR(11) NOT NULL,
        USUARIO_ROLE DM_ROLE NOT NULL,
        SENHA VARCHAR(255),
        CODIGO VARCHAR(6),
        ATIVO BOOLEAN DEFAULT FALSE NOT NULL,
PRIMARY KEY (ID_USUARIO));

/*  Index definitions for all user tables */
CREATE INDEX IX_AVALIACAO_PROFISSIONAL ON AVALIACAO (PROFISSIONAL_ID);
CREATE INDEX IDX_REGISTRO_USUARIO_DATA ON REGISTRO (USUARIO_ID, CRIADO_EM);

ALTER TABLE AVALIACAO ADD CONSTRAINT FK_AVALIACAO_PACIENTE FOREIGN KEY (PACIENTE_ID) REFERENCES USUARIO (ID_USUARIO) ON DELETE CASCADE;

ALTER TABLE AVALIACAO ADD CONSTRAINT FK_AVALIACAO_PROFISSIONAL FOREIGN KEY (PROFISSIONAL_ID) REFERENCES PROFISSIONAL (USUARIO_ID) ON DELETE CASCADE;

ALTER TABLE AVALIACAO ADD CONSTRAINT FK_AVALIACAO_SESSAO FOREIGN KEY (SESSAO_ID) REFERENCES SESSAO (SESSAO_ID) ON DELETE CASCADE;

ALTER TABLE CONVERSA_MENSAGEM ADD CONSTRAINT FK_MENSAGEM_CONVERSA FOREIGN KEY (CONVERSA_ID) REFERENCES CONVERSA (CONVERSA_ID) ON DELETE CASCADE;

ALTER TABLE CONVERSA_MENSAGEM ADD CONSTRAINT FK_MENSAGEM_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID_USUARIO) ON DELETE CASCADE;

ALTER TABLE ENCAMINHAMENTO ADD CONSTRAINT FK_ENCAM_PACIENTE FOREIGN KEY (PACIENTE_ID) REFERENCES USUARIO (ID_USUARIO) ON DELETE CASCADE;

ALTER TABLE ENCAMINHAMENTO ADD CONSTRAINT FK_ENCAM_PSICOLOGO FOREIGN KEY (PSICOLOGO_ID) REFERENCES PROFISSIONAL (USUARIO_ID) ON DELETE CASCADE;

ALTER TABLE PROFISSIONAL ADD CONSTRAINT FK_PROFISSIONAL_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID_USUARIO) ON DELETE CASCADE;

ALTER TABLE REGISTRO ADD CONSTRAINT FK_REGISTRO_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID_USUARIO) ON DELETE CASCADE;

ALTER TABLE SESSAO ADD CONSTRAINT FK_SESSAO_CONVERSA FOREIGN KEY (CONVERSA_ID) REFERENCES CONVERSA (CONVERSA_ID) ON DELETE SET NULL;

ALTER TABLE SESSAO ADD CONSTRAINT FK_SESSAO_ENCAMINHAMENTO FOREIGN KEY (ENCAMINHAMENTO_ID) REFERENCES ENCAMINHAMENTO (ENCAMINHAMENTO_ID) ON DELETE SET NULL;

ALTER TABLE SESSAO ADD CONSTRAINT FK_SESSAO_PACIENTE FOREIGN KEY (PACIENTE_ID) REFERENCES USUARIO (ID_USUARIO) ON DELETE CASCADE;

ALTER TABLE SESSAO ADD CONSTRAINT FK_SESSAO_PROFISSIONAL FOREIGN KEY (PROFISSIONAL_ID) REFERENCES PROFISSIONAL (USUARIO_ID) ON DELETE CASCADE;

/* Domain constraints */
ALTER DOMAIN DM_CONSELHO ADD CONSTRAINT
         CHECK (VALUE IN ('CRP', 'CRM'));
ALTER DOMAIN DM_MODALIDADE ADD CONSTRAINT
         CHECK (VALUE IN ('ONLINE', 'PRESENCIAL', 'AMBAS'));
ALTER DOMAIN DM_NIVEL_HUMOR ADD CONSTRAINT
         CHECK (VALUE IN ('PESSIMO', 'RUIM', 'NEUTRO', 'BOM', 'EXCELENTE'));
ALTER DOMAIN DM_QUALIDADE_ALIMENTACAO ADD CONSTRAINT
         CHECK (VALUE IN ('POUCA', 'DESREGULADA', 'ADEQUADA', 'EXCESSIVA'));
ALTER DOMAIN DM_QUALIDADE_SONO ADD CONSTRAINT
         CHECK (VALUE IN ('RUIM', 'REGULAR', 'BOA', 'EXCELENTE'));
ALTER DOMAIN DM_ROLE ADD CONSTRAINT
         CHECK (VALUE IN ('PACIENTE', 'PSICOLOGO', 'PSIQUIATRA'));
ALTER DOMAIN DM_STATUS_ENCAMINHAMENTO ADD CONSTRAINT
         CHECK (VALUE IN ('ATIVO', 'CONCLUIDO', 'CANCELADO'));
ALTER DOMAIN DM_STATUS_SESSAO ADD CONSTRAINT
         CHECK (VALUE IN ('AGENDADO', 'CONFIRMADO', 'REALIZADO', 'CANCELADO'));

/* Table constraints */

ALTER TABLE AVALIACAO ADD 
        CHECK (NOTA BETWEEN 1 AND 5);
