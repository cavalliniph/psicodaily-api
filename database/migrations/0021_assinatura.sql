-- 9: assinatura do profissional. ASSINATURA e o estado atual (uma linha por profissional): o plano vale ate
-- VALIDA_ATE, inclusive; sem plano valido o profissional some da busca. PLANO_PROXIMO e o downgrade agendado.
CREATE TABLE ASSINATURA (PROFISSIONAL_ID INTEGER NOT NULL,
        PLANO VARCHAR(12) NOT NULL,
        VALIDA_ATE DATE NOT NULL,
        RENOVAR BOOLEAN DEFAULT TRUE NOT NULL,
        PLANO_PROXIMO VARCHAR(12),
        CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
PRIMARY KEY (PROFISSIONAL_ID),
CONSTRAINT CK_ASSINATURA_PLANO CHECK (PLANO IN ('ESSENCIAL', 'PROFISSIONAL', 'PREMIUM')),
CONSTRAINT CK_ASSINATURA_PLANO_PROXIMO CHECK (PLANO_PROXIMO IS NULL OR PLANO_PROXIMO IN ('ESSENCIAL', 'PROFISSIONAL', 'PREMIUM')));
ALTER TABLE ASSINATURA ADD CONSTRAINT FK_ASSINATURA_PROFISSIONAL FOREIGN KEY (PROFISSIONAL_ID) REFERENCES PROFISSIONAL (USUARIO_ID) ON DELETE CASCADE;

-- Cada mes e uma cobranca avulsa na Arkhé (ela nao tem recorrencia). Como em PAGAMENTO, o id so e unico dentro do metodo.
CREATE TABLE COBRANCA_ASSINATURA (COBRANCA_ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
        PROFISSIONAL_ID INTEGER NOT NULL,
        PLANO VARCHAR(12) NOT NULL,
        METODO VARCHAR(10) NOT NULL,
        ID_COBRANCA_ARKHE INTEGER NOT NULL,
        VALOR_CENTAVOS INTEGER NOT NULL,
        STATUS VARCHAR(10) DEFAULT 'PENDENTE' NOT NULL,
        CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
        PAGO_EM TIMESTAMP,
PRIMARY KEY (COBRANCA_ID),
CONSTRAINT UQ_COBRANCA_ASSINATURA_ARKHE UNIQUE (METODO, ID_COBRANCA_ARKHE),
CONSTRAINT CK_COBRANCA_ASSINATURA_PLANO CHECK (PLANO IN ('ESSENCIAL', 'PROFISSIONAL', 'PREMIUM')),
CONSTRAINT CK_COBRANCA_ASSINATURA_METODO CHECK (METODO IN ('PIX', 'BOLETO', 'CARTAO')),
CONSTRAINT CK_COBRANCA_ASSINATURA_STATUS CHECK (STATUS IN ('PENDENTE', 'PAGO')));
ALTER TABLE COBRANCA_ASSINATURA ADD CONSTRAINT FK_COBRANCA_ASSINATURA_PROF FOREIGN KEY (PROFISSIONAL_ID) REFERENCES PROFISSIONAL (USUARIO_ID) ON DELETE CASCADE;
CREATE INDEX IX_COBRANCA_ASSINATURA_STATUS ON COBRANCA_ASSINATURA (STATUS, CRIADO_EM);

-- Visualizacoes do perfil por dia (beneficio do plano Profissional)
CREATE TABLE VISUALIZACAO_PERFIL (PROFISSIONAL_ID INTEGER NOT NULL,
        DIA DATE NOT NULL,
        TOTAL INTEGER NOT NULL,
PRIMARY KEY (PROFISSIONAL_ID, DIA));
ALTER TABLE VISUALIZACAO_PERFIL ADD CONSTRAINT FK_VISUALIZACAO_PERFIL_PROF FOREIGN KEY (PROFISSIONAL_ID) REFERENCES PROFISSIONAL (USUARIO_ID) ON DELETE CASCADE;
